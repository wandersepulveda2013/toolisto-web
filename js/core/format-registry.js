export function getFormatInfo(format) {
  return formats[format] || formats.unknown;
}

export function getToolsForFormat(format) {
  const info = getFormatInfo(format);
  return info.tools || [];
}

export function canProcessInTool(format, toolKey) {
  const info = getFormatInfo(format);
  return (info.tools || []).includes(toolKey);
}

export function getUnsupportedMessage(format) {
  const info = getFormatInfo(format);
  if (info.status === STATUS.NOT_IMPLEMENTED) {
    return 'Este formato todavía no está disponible en Toolisto.';
  }
  if (info.status === STATUS.DETECTED && !info.processable) {
    return info.browserNote || `${info.name} está detectado pero aún no se puede procesar.`;
  }
  return null;
}

export function getAllFormats() {
  return Object.keys(formats).filter(f => f !== 'unknown');
}

export function getFormatsByCategory(category) {
  return Object.entries(formats)
    .filter(([key, info]) => info.category === category && key !== 'unknown')
    .map(([key]) => key);
}

export function isFormatProcessable(format) {
  const info = getFormatInfo(format);
  return info.processable === true;
}
